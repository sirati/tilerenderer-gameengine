    #[test]
    fn z_rebases_free_order_world_points_without_moving_physical_gesture_points() {
        for confirming in [false, true] {
            let mut l = layout();
            preview(&mut l, (100, 100), (170, 190));
            if confirming {
                button(&mut l, Button::Left, true, (170, 190));
            } else {
                button(&mut l, Button::Right, true, (170, 190));
                mv(&mut l, (180, 200));
            }
            let original = if confirming { l.unit_orders.confirm.unwrap() } else { l.unit_orders.right.unwrap() };
            let target = l.unit_orders.destination.unwrap();
            l.unit_orders_rescale_world(0.5);
            let rebased = if confirming { l.unit_orders.confirm.unwrap() } else { l.unit_orders.right.unwrap() };
            assert_eq!(rebased.point.world, ((original.point.world.0 as f64 * 0.5).round() as i32, (original.point.world.1 as f64 * 0.5).round() as i32));
            assert_eq!(rebased.point.motion, original.point.motion);
            assert_eq!(rebased.window, original.window);
            assert_eq!(rebased.dragging, original.dragging);
            assert_eq!(l.unit_orders.destination, Some(((target.0 as f64 * 0.5).round() as i32, (target.1 as f64 * 0.5).round() as i32)));
            assert!(l.take_unit_order_events().is_empty());
        }
    }

